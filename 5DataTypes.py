# 1. What is a Data Type?
# A data type defines the type of value that a variable can store.

# For example:
# - 10 is an integer.
# - 10.5 is a decimal number.
# - "Prashant" is a string.
# - True is a Boolean value.
# In simple words, a data type tells Python what kind of data is being stored.
# 2. Main Data Types in Python
# Python has several built-in data types.
# Data type	Meaning	Example
# int	Integer numbers	10, 25, -5
# float	Decimal numbers	10.5, 3.14
# complex	Complex numbers	2+3j
# str	Text or strings	"Hello"
# bool	True or False	True, False
# list	Collection of values	[10, 20, 30]
# tuple	Ordered collection	(10, 20, 30)
# set	Unique values	{10, 20, 30}
# dict	Key-value pairs	{"name": "Prashant"}

