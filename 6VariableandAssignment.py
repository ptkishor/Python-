# 1. What is a Variable?
# A variable is a named memory location used to store data in a program.

# In simple words, a variable is like a container that stores a value.

#Example:


name = "Prashant"
age = 20
marks = 25

# Here:
# - name stores "Prashant".
# - age stores 20.
# - marks stores 25.


# 2. What is Assignment?
# Assignment means giving or storing a value in a variable.

# The assignment operator in Python is: =


# Example: 

age = 20


# Here:
# - age is the variable name.
# - = is the assignment operator.
# - 20 is the value assigned.

# Important: In Python, = means assignment, not equality comparison.