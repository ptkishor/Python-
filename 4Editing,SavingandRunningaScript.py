# 1. What is a Python Script?
# A Python script is a file that contains Python code and is saved with the .py extension.

# Example:

# hello.py

# It contains:
# print("Hello, World!")print("Welcome to Python")



# Unlike the Interactive Shell, a script allows us to write and save multiple Python statements in one file.
# 2. Editing a Python Script
# Editing means writing or modifying Python code using a text editor or code editor.

# Common editors include:
# - IDLE (Python's built-in editor)
# - Visual Studio Code
# - Notepad
# - PyCharm







# tutorialsteacher.com


# 3. Saving a Python Script
# Follow these steps:
# 1. Open a code editor.
# 2. Write your Python code.
# 3. Click File → Save As.
# 4. Enter a filename, for example hello.py.
# 5. Select a folder.
# 6. Click Save.
# Important: The .py extension identifies a Python source-code file.
# 4. Running a Python Script
# There are two common ways to run a Python script.

# Method 1: Using the editor

# In Python IDLE:
# 1. Open your .py file.
# 2. Click Run.
# 3. Select Run Module (or press F5).
# 4. The output appears in the Python Shell.
# Method 2: Using Command Prompt

# Open Command Prompt, navigate to the folder containing your file, and type:
# python hello.py


